#!/usr/bin/env node
/**
 * Keeps the app version in one place: package.json.
 * Rewrites src/main/version.ts, snapcraft.yaml and the Flatpak metainfo release.
 *
 *   node scripts/sync-version.mjs [version]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkgPath = path.join(root, 'package.json')
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
const version = process.argv[2] ?? pkg.version

if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`Invalid semver: ${version}`)
  process.exit(1)
}

if (version !== pkg.version) {
  pkg.version = version
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`)
}

writeFileSync(
  path.join(root, 'src/main/version.ts'),
  `// Generated by scripts/sync-version.mjs — do not edit by hand.\nexport const APP_VERSION = '${version}'\nexport const APP_NAME = 'GitGrove'\n`
)

const snapPath = path.join(root, 'snap/snapcraft.yaml')
const snap = readFileSync(snapPath, 'utf8').replace(/^version: .*$/m, `version: '${version}'`)
writeFileSync(snapPath, snap)

const metaPath = path.join(root, 'flatpak/dev.gitgrove.GitGrove.metainfo.xml')
const meta = readFileSync(metaPath, 'utf8')
if (!meta.includes(`version="${version}"`)) {
  const today = new Date().toISOString().slice(0, 10)
  writeFileSync(
    metaPath,
    meta.replace(
      /<releases>/,
      `<releases>\n    <release version="${version}" date="${today}">\n      <description>\n        <p>See the changelog for details.</p>\n      </description>\n    </release>`
    )
  )
}

console.log(`version synced: ${version}`)